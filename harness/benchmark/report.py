# harness/benchmark/report.py — Benchmark Report Generation (V3.0)
"""
Generates structured benchmark reports from execution results.
Produces markdown reports with summary, per-scenario details, and trend analysis.
"""

from typing import Any, Dict, List, Optional
from datetime import datetime
import os


class BenchmarkReportGenerator:
    """Generates benchmark reports in markdown format."""

    def __init__(self, output_dir: str = ""):
        self.output_dir = output_dir or os.path.join(
            os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            "..", "artifacts", "benchmarks"
        )
        os.makedirs(self.output_dir, exist_ok=True)

    def generate(self, results: List[Any], summary: Dict[str, Any],
                 baseline: Optional[Dict[str, Any]] = None,
                 tags: Optional[List[str]] = None) -> str:
        """Generate a full benchmark report as markdown."""
        lines = []

        # Header
        lines.append("# Engineering Benchmark Report")
        lines.append("")
        lines.append(f"**Generated:** {datetime.utcnow().isoformat()}")
        if tags:
            lines.append(f"**Tags:** {', '.join(tags)}")
        lines.append("")

        # Summary
        lines.append("## Summary")
        lines.append("")
        lines.append(f"| Metric | Value |")
        lines.append(f"|--------|-------|")
        lines.append(f"| Total Scenarios | {summary['total_scenarios']} |")
        lines.append(f"| Passed | {summary['passed']} |")
        lines.append(f"| Failed | {summary['failed']} |")
        lines.append(f"| Pass Rate | {summary['pass_rate']:.1f}% |")
        lines.append(f"| Avg Duration | {summary['avg_duration_seconds']:.1f}s |")
        lines.append(f"| Total Duration | {summary['total_duration_seconds']:.1f}s |")
        lines.append("")

        # Baseline comparison
        if baseline:
            lines.append("## Baseline Comparison")
            lines.append("")
            old_rate = baseline.get("pass_rate", 0)
            new_rate = summary["pass_rate"]
            delta = new_rate - old_rate
            arrow = "↑" if delta > 0 else "↓" if delta < 0 else "→"
            lines.append(f"| Metric | V2.2 Baseline | V3.0 | Delta |")
            lines.append(f"|--------|--------------|------|-------|")
            lines.append(f"| Pass Rate | {old_rate:.1f}% | {new_rate:.1f}% | {arrow} {abs(delta):.1f}% |")
            lines.append(f"| Avg Duration | {baseline.get('avg_duration_seconds', 0):.1f}s | {summary['avg_duration_seconds']:.1f}s | → |")
            lines.append("")

        # Per-scenario results
        lines.append("## Scenario Results")
        lines.append("")
        lines.append("| Scenario | Status | Duration | Capabilities Used | Error |")
        lines.append("|----------|--------|----------|-------------------|-------|")

        for result in sorted(results, key=lambda r: r.scenario_id):
            status_icon = "✅" if result.status == "PASSED" else "❌" if result.status == "FAILED" else "⚠️"
            cap_summary = ", ".join(result.capabilities_used[:5])
            if len(result.capabilities_used) > 5:
                cap_summary += "..."
            error = (result.error or "")[:80]
            lines.append(
                f"| {result.scenario_name} "
                f"| {status_icon} {result.status} "
                f"| {result.duration_seconds:.1f}s "
                f"| {cap_summary} "
                f"| {error} |"
            )

        lines.append("")
        lines.append("## Capability Coverage")
        lines.append("")

        # Aggregate capability usage
        cap_stats: Dict[str, int] = {}
        for result in results:
            for cap in result.capabilities_used:
                cap_stats[cap] = cap_stats.get(cap, 0) + 1

        if cap_stats:
            lines.append("| Capability | Used In |")
            lines.append("|------------|---------|")
            for cap, count in sorted(cap_stats.items(), key=lambda x: -x[1]):
                lines.append(f"| {cap} | {count} scenario(s) |")
        else:
            lines.append("_No capability data collected._")

        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append("_Report generated by BenchmarkEngine_")

        return "\n".join(lines)

    def save(self, report: str, filename: str = "") -> str:
        """Save report to file."""
        filename = filename or f"benchmark_report_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.md"
        path = os.path.join(self.output_dir, filename)
        with open(path, "w") as f:
            f.write(report)
        return path
